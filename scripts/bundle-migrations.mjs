#!/usr/bin/env node
/**
 * Embed prisma/migrations/*\/migration.sql into src/generated/migrations.ts so the server can apply
 * them at start-up (src/server/db/bootstrap.ts) without reading the repo's files at runtime.
 * Runs on install (via prisma-generate.mjs) and before every build. Output is gitignored.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "prisma", "migrations");
const OUT = path.join(ROOT, "src", "generated", "migrations.ts");

const migrations = fs
  .readdirSync(DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(DIR, d.name, "migration.sql")))
  .map((d) => d.name)
  .sort()
  .map((name) => ({ name, sql: fs.readFileSync(path.join(DIR, name, "migration.sql"), "utf8") }));

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  `// Generated by scripts/bundle-migrations.mjs — do not edit.\nimport type { Migration } from "@/server/db/migrator";\n\nexport const MIGRATIONS: Migration[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`[bundle-migrations] ${migrations.length} migration(s) → src/generated/migrations.ts`);
